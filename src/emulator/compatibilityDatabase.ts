export function lookupGameInfo(gameId: string): Partial<GameMetadata> {
  const normalizedId = gameId.trim().toUpperCase();
  if (COMPATIBILITY_DATABASE[normalizedId]) {
    return COMPATIBILITY_DATABASE[normalizedId];
  }
  // Try 4-character prefix
  const prefix4 = normalizedId.slice(0, 4);
  for (const [key, value] of Object.entries(COMPATIBILITY_DATABASE)) {
    if (key.startsWith(prefix4)) {
      return value;
    }
  }
  const isWii = gameId.startsWith('R') || gameId.startsWith('S') || gameId.startsWith('H') || gameId.startsWith('D');
  const regionChar = gameId.charAt(3);
  const region = regionChar === 'E' ? 'USA' : regionChar === 'P' ? 'EUR' : regionChar === 'J' ? 'JPN' : 'WORLD';

  return {
    id: gameId,
    title: `Game (${gameId})`,
    console: isWii ? 'WII' : 'GAMECUBE',
    format: 'ISO',
    region: region,
    compatibility: 'PLAYABLE',
    recommendedBackend: 'vulkan',
    fileSize: isWii ? '4.37 GB' : '1.35 GB',
    notes: 'Standard Dolphin game profile automatically loaded. Virtual 1T-SRAM & GX pipeline configured.',
    coverImage: `https://art.gametdb.com/wii/cover/${region === 'EUR' ? 'EN' : region === 'JPN' ? 'JA' : 'US'}/${gameId.slice(0, 6)}.jpg`,
  };
}
